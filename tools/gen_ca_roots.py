"""Generate firmware/lib/robot_hw/src/ca_roots.h from Mozilla's CA bundle (certifi).

The robot validates the gateway's TLS certificate against these public root CAs, which
cover the common hosting providers (Let's Encrypt, Google Trust Services, DigiCert, Amazon,
Microsoft, GlobalSign, SSL.com). If your gateway's certificate chains to a different root,
add its subject name below and re-run:

    pip install certifi
    python tools/gen_ca_roots.py
"""
from __future__ import annotations

import re
from pathlib import Path

import certifi

WANTED = [
    "ISRG Root X1", "ISRG Root X2",                       # Let's Encrypt (Fly.io, Render, Railway, many VPS)
    "GTS Root R1", "GTS Root R2", "GTS Root R3", "GTS Root R4",  # Google Cloud Run / Firebase
    "GlobalSign Root CA",                                  # Google cross-sign
    "DigiCert Global Root CA", "DigiCert Global Root G2",  # Azure, many CDNs
    "Amazon Root CA 1", "Amazon Root CA 3",                # AWS
    "Microsoft RSA Root Certificate Authority 2017",
    "SSL.com Root Certification Authority RSA",            # Cloudflare edge (some zones)
]

OUT = Path(__file__).resolve().parents[1] / "firmware/lib/robot_hw/src/ca_roots.h"


def main() -> None:
    pem = Path(certifi.where()).read_text(encoding="ascii")
    blocks = re.findall(r'# Label: "([^"]+)"\n.*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', pem, re.S)
    found = {label: cert for label, cert in blocks if label in WANTED}
    missing = [w for w in WANTED if w not in found]
    lines = [
        "// GENERATED by tools/gen_ca_roots.py from certifi " + certifi.__version__ + " - do not edit.",
        "// Public root CAs trusted for the AI gateway's HTTPS certificate.",
        "#pragma once",
        "",
        "static const char kGatewayRootCAs[] =",
    ]
    for name in WANTED:
        if name not in found:
            continue
        lines.append(f"    // {name}")
        for row in found[name].splitlines():
            lines.append(f'    "{row}\\n"')
    lines += ["    ;", ""]
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT} with {len(found)} roots; missing: {missing or 'none'}")


if __name__ == "__main__":
    main()
