"""Generate firmware/lib/robot_logic/src/offline_content.h.

The robot has no Arabic shaping engine, so Arabic captions are pre-shaped here into
presentation forms in visual (left-to-right display) order, exactly like the gateway does
for live replies. Re-run after editing the word lists:

    pip install arabic-reshaper python-bidi
    python tools/gen_offline_content.py
"""
from __future__ import annotations

from pathlib import Path

import arabic_reshaper
from bidi.algorithm import get_display

OUT = Path(__file__).resolve().parents[1] / "firmware/lib/robot_logic/src/offline_content.h"

EN_ALPHABET = [
    ("A", "Apple"), ("B", "Ball"), ("C", "Cat"), ("D", "Dog"), ("E", "Elephant"), ("F", "Fish"),
    ("G", "Grapes"), ("H", "Hat"), ("I", "Ice cream"), ("J", "Juice"), ("K", "Kite"), ("L", "Lion"),
    ("M", "Moon"), ("N", "Nest"), ("O", "Orange"), ("P", "Pencil"), ("Q", "Queen"), ("R", "Rabbit"),
    ("S", "Sun"), ("T", "Tree"), ("U", "Umbrella"), ("V", "Violin"), ("W", "Whale"),
    ("X", "Xylophone"), ("Y", "Yo-yo"), ("Z", "Zebra"),
]

# (letter, example word, English gloss) — simple nouns a young child knows.
AR_ALPHABET = [
    ("ا", "أسد", "lion"), ("ب", "بطة", "duck"), ("ت", "تفاحة", "apple"), ("ث", "ثعلب", "fox"),
    ("ج", "جمل", "camel"), ("ح", "حصان", "horse"), ("خ", "خروف", "sheep"), ("د", "دب", "bear"),
    ("ذ", "ذرة", "corn"), ("ر", "رمان", "pomegranate"), ("ز", "زرافة", "giraffe"), ("س", "سمكة", "fish"),
    ("ش", "شمس", "sun"), ("ص", "صقر", "falcon"), ("ض", "ضفدع", "frog"), ("ط", "طائرة", "airplane"),
    ("ظ", "ظرف", "envelope"), ("ع", "عصفور", "sparrow"), ("غ", "غزال", "gazelle"), ("ف", "فيل", "elephant"),
    ("ق", "قطة", "cat"), ("ك", "كتاب", "book"), ("ل", "ليمون", "lemon"), ("م", "موز", "banana"),
    ("ن", "نحلة", "bee"), ("ه", "هدية", "gift"), ("و", "وردة", "rose"), ("ي", "يد", "hand"),
]

ONES = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten",
        "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen",
        "nineteen"]
TENS = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"]


def number_word(n: int) -> str:
    if n == 100:
        return "one hundred"
    if n < 20:
        return ONES[n]
    t, o = divmod(n, 10)
    return TENS[t] + ("" if o == 0 else "-" + ONES[o])


def visual(text: str) -> str:
    return get_display(arabic_reshaper.reshape(text))


def c_string(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if b < 0x80 and ch not in '"\\':
            out.append(ch)
        else:
            out.append(f"\\x{b:02X}\"\"")  # split after hex escapes so following hex digits are safe
    return '"' + "".join(out) + '"'


def main() -> None:
    lines = [
        "// GENERATED by tools/gen_offline_content.py — do not edit by hand.",
        "// Offline learning cards shown when the AI gateway is unreachable.",
        "// Arabic captions are pre-shaped (presentation forms, visual order) for the OLED.",
        "#pragma once",
        "",
        "namespace robot {",
        "namespace offline {",
        "",
        "struct LetterCard {",
        "  const char* letter;",
        "  const char* caption;",
        "  bool rtl;",
        "};",
        "",
        f"constexpr int kEnLetters = {len(EN_ALPHABET)};",
        "constexpr LetterCard kEnAlphabet[kEnLetters] = {",
    ]
    for letter, word in EN_ALPHABET:
        lines.append(f"    {{{c_string(letter)}, {c_string(f'{letter} is for {word}')}, false}},")
    lines += ["};", "", f"constexpr int kArLetters = {len(AR_ALPHABET)};",
              "constexpr LetterCard kArAlphabet[kArLetters] = {"]
    for letter, word, gloss in AR_ALPHABET:
        lines.append(f"    {{{c_string(letter)}, {c_string(visual(word))}, true}},  // {word} = {gloss}")
    lines += ["};", "", "constexpr const char* kNumberWords[101] = {"]
    for n in range(0, 101):
        lines.append(f"    {c_string(number_word(n))},")
    lines += ["};", "", "}  // namespace offline", "}  // namespace robot", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
